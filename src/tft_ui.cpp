// Change these if they are in use on your board.
// This is the LCD's main SPI interface, NOT its T-CLK/T-DIN touch interface.
static constexpr gpio_num_t TFT_MOSI = GPIO_NUM_23; // SDI(MOSI)
static constexpr gpio_num_t TFT_SCLK = GPIO_NUM_18; // SCK
static constexpr gpio_num_t TFT_CS   = GPIO_NUM_5;  // CS
static constexpr gpio_num_t TFT_DC   = GPIO_NUM_4;  // DC
static constexpr gpio_num_t TFT_RST  = GPIO_NUM_32; // RESET
// TFT LED pin: supply as appropriate for the module; no backlight GPIO used here.
static constexpr int W = 320, H = 240, STRIPE = 16;
static constexpr uint16_t BG=0x000D, WHITE=0xFFFF, CYAN=0x07FF,
                          GREEN=0x07E0, GRAY=0xC618;
static spi_device_handle_t spi;
static uint16_t *pixels;
static int stripeY;

static void send(bool data, const uint8_t *buf, size_t len) {
  gpio_set_level(TFT_DC, data);
  spi_transaction_t t = {};
  t.length = len*8;
  t.tx_buffer = buf;
  ESP_ERROR_CHECK(spi_device_polling_transmit(spi,&t));
}
static void cmd(uint8_t c) { send(false,&c,1); }
static void args(std::initializer_list<uint8_t> bytes) {
  uint8_t buf[32]; int n=0;
  for (auto b:bytes) buf[n++]=b;
  send(true,buf,n);
}
static void window(int x1,int y1,int x2,int y2) {
  cmd(0x2A); args({uint8_t(x1>>8),uint8_t(x1),uint8_t(x2>>8),uint8_t(x2)});
  cmd(0x2B); args({uint8_t(y1>>8),uint8_t(y1),uint8_t(y2>>8),uint8_t(y2)});
  cmd(0x2C);
}
void tftUiInit() {
  gpio_config_t io = {};
  io.pin_bit_mask = (1ULL<<TFT_DC) | (1ULL<<TFT_RST);
  io.mode = GPIO_MODE_OUTPUT;
  ESP_ERROR_CHECK(gpio_config(&io));
  gpio_set_level(TFT_RST,0);
  vTaskDelay(pdMS_TO_TICKS(30));
  gpio_set_level(TFT_RST,1);
  vTaskDelay(pdMS_TO_TICKS(120));
  spi_bus_config_t bus = {};
  bus.mosi_io_num = TFT_MOSI;
  bus.miso_io_num = -1;
  bus.sclk_io_num = TFT_SCLK;
  bus.quadwp_io_num = -1;
  bus.quadhd_io_num = -1;
  bus.max_transfer_sz = W*STRIPE*2+16;
  ESP_ERROR_CHECK(spi_bus_initialize(SPI2_HOST,&bus,SPI_DMA_CH_AUTO));
  spi_device_interface_config_t dev = {};
  dev.clock_speed_hz = 20000000;
  dev.mode = 0;
  dev.spics_io_num = TFT_CS;
  dev.queue_size = 1;
  ESP_ERROR_CHECK(spi_bus_add_device(SPI2_HOST,&dev,&spi));
  // Standard ILI9341 init; TFT must have an ILI9341-compatible controller.
  cmd(0x01); vTaskDelay(pdMS_TO_TICKS(150));
  cmd(0x28);
  cmd(0x3A); args({0x55}); // RGB565, 16-bit pixels
  cmd(0x36); args({0x28}); // landscape orientation, BGR
  cmd(0x11); vTaskDelay(pdMS_TO_TICKS(120));
  cmd(0x29); vTaskDelay(pdMS_TO_TICKS(20));
  pixels=(uint16_t*)heap_caps_malloc(W*STRIPE*2,MALLOC_CAP_DMA|MALLOC_CAP_INTERNAL);
  ESP_ERROR_CHECK(pixels ? ESP_OK : ESP_ERR_NO_MEM);
}
static void rect(int x,int y,int w,int h,uint16_t color) {
  if(w<=0||h<=0) return;
  int x1=x<0?0:x, x2=x+w>W?W:x+w;
  int y1=y<stripeY?stripeY:y, y2=y+h>stripeY+STRIPE?stripeY+STRIPE:y+h;
  if(x2<=x1||y2<=y1) return;
  uint16_t c=(uint16_t)((color>>8)|(color<<8)); // SPI big-endian RGB565
  for(int yy=y1; yy<y2; ++yy)
    for(int xx=x1; xx<x2; ++xx) pixels[(yy-stripeY)*W+xx]=c;
}
static void outline(int x,int y,int w,int h,uint16_t color) {
  rect(x,y,w,2,color);rect(x,y+h-2,w,2,color);
  rect(x,y,2,h,color);rect(x+w-2,y,2,h,color);
}

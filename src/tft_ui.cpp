static void glyph(int x,int y,char c,uint16_t color,int scale) {
  if(c<32||c>126) c='?';
  const uint8_t *g=&FONT[(c-32)*10];
  for(int yy=0;yy<10;yy++) for(int xx=0;xx<6;xx++)
    if(g[yy] & (1<<(5-xx))) rect(x+xx*scale,y+yy*scale,scale,scale,color);
}
static void str(int x,int y,const char *s,uint16_t color,int scale=1) {
  for(;*s && x<W-5*scale;s++,x+=7*scale) glyph(x,y,*s,color,scale);
}
static void item(int row, int selected,int start, const char *name,const char *val,bool editing) {
  const int y=68+row*23;
  if(selected==start+row) {
    outline(7,y-3,306,22,editing?GREEN:CYAN);
    str(13,y,editing?"*":">",CYAN);
  }
  str(30,y,name,WHITE);
  str(217,y,val,selected==start+row && editing ? GREEN:WHITE);
}
void tftUiDraw(const TftUiState &s) {
  const int total=4+s.otherCount;
  int first=0;
  if(s.selected>=4) first=s.selected-3;
  if(first>total-5) first=total-5;
  if(first<0) first=0;
  char val[32];
  for(stripeY=0;stripeY<H;stripeY+=STRIPE) {
    rect(0,stripeY,W,STRIPE,BG);
    str(12,8,"STEPPER SYNTH",WHITE,2);
    const char *status=s.recordingState==1?"REC":s.recordingState==2?"PLAY":s.recordingState==3?"PAUSE":s.activeVoices?"ON":"IDLE";
    str(255,11,status,s.recordingState==1?CYAN:GREEN,1);
    rect(8,33,304,2,GRAY);
    str(10,42,first<4?"VOLUME ENVELOPE":"SETTINGS",WHITE);
    str(245,42,s.editing?"EDIT":"BROWSE",GRAY);
    for(int row=0;row<5;row++) {
      int index=first+row;
      if(index>=total) break;
      switch(index) {
        case 0: snprintf(val,sizeof(val),"%d ms",s.attackMs);item(row,s.selected,index,"Attack",val,s.editing);break;
        case 1: snprintf(val,sizeof(val),"%d ms",s.decayMs);item(row,s.selected,index,"Decay",val,s.editing);break;
        case 2: snprintf(val,sizeof(val),"%d%%",s.sustainPct);item(row,s.selected,index,"Sustain",val,s.editing);break;
        case 3: snprintf(val,sizeof(val),"%d ms",s.releaseMs);item(row,s.selected,index,"Release",val,s.editing);break;
        default: item(row,s.selected,index,s.otherNames[index-4],s.otherValues[index-4],s.editing);break;
      }
    }
    rect(8,186,304,2,GRAY);
    snprintf(val,sizeof(val),"VOICES %d / 3",s.activeVoices);
    str(12,193,val,WHITE);
    str(210,193,"REC",GRAY);
    str(246,193,s.recordingState==1?"ON":s.hasRecording?"SAVED":"EMPTY",GREEN);
    rect(8,209,304,2,GRAY);
    str(12,216,s.editing?"Rotate: change value":"Rotate: select parameter",WHITE);
    str(12,228,s.editing?"Press: finish editing":"Press: edit value",GRAY);
    window(0,stripeY,W-1,stripeY+STRIPE-1);
    send(true,(uint8_t*)pixels,W*STRIPE*2);
  }
}
